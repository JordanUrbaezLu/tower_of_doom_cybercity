# the cards
def zoned_cards():
    text = open(ZONE, encoding='utf-8').read()
    names = []
    for m in re.finditer(r'^image,(i_tod_card_[a-z0-9_]+)\s*$', text, re.M):
        n = m.group(1)
        if re.match(r'i_tod_card_tier_[a-z]+_[23]$', n) or re.match(r'i_tod_card_.+_(regular|super|ultimate)$', n):
            if n.startswith('i_tod_cardpip_'):
                continue
            names.append(n)
    return sorted(set(names))


def band_view(a):
    x0, y0, x1, y1 = BAND
    return a[y0:y1, x0:x1]


def panel_colour(a):
    band = band_view(a)[..., :3].reshape(-1, 3)
    vals, counts = np.unique(band, axis=0, return_counts=True)
    return tuple(int(v) for v in vals[counts.argmax()])


def band_clean(a):
    band = band_view(a)[..., :3]
    return bool((band == band[0, 0]).all())


def find_dots(a, panel):
    """Centres of the baked dots: a dot (lit or empty) never has a panel-coloured
    centre, and every baked row sits on the 29 px half-pitch grid about x 384."""
    found = []
    for s in range(-8, 9):
        cx = int(PIP_CX + s * (PIP_PITCH / 2.0))
        cy = int(PIP_CY)
        core = a[cy - 1:cy + 1, cx - 1:cx + 1, :3].astype(int)
        if (np.abs(core - panel).sum(axis=2) > 24).all():
            found.append(float(cx))
    return found


def paint_out(a):
    """Returns (new_array, n_dots) or raises ValueError when the band holds anything
    that is not one of the detected dots."""
    out = a.copy()
    x0, y0, x1, y1 = BAND
    panel = np.array(panel_colour(a))
    band = out[y0:y1, x0:x1]
    diff = np.abs(band[..., :3].astype(int) - panel).sum(axis=2) > 0
    if not diff.any():
        return out, 0
    dots = find_dots(a, panel)
    if not dots:
        raise ValueError('off-panel pixels in the dot band but no dot centre on the grid')
    for i in range(1, len(dots)):
        if dots[i] - dots[i - 1] < PIP_PITCH - 0.5:
            raise ValueError('dots closer than the baked pitch at x %.0f / %.0f' % (dots[i - 1], dots[i]))
    ys, xs = np.nonzero(diff)
    xs = xs + x0 + 0.5
    ys = ys + y0 + 0.5
    # every off-panel pixel must sit inside the footprint of a DETECTED dot
    r = np.min(np.stack([np.sqrt((xs - cx) ** 2 + (ys - PIP_CY) ** 2) for cx in dots]), axis=0)
    if (r > R_HALO + 1.5).any():
        bad = int((r > R_HALO + 1.5).sum())
        raise ValueError('%d off-panel pixel(s) in the dot band that belong to no dot' % bad)
    keep_alpha = band[..., 3].copy()
    band[diff, 0], band[diff, 1], band[diff, 2] = panel
    band[..., 3] = keep_alpha
    return out, len(dots)


def sha(path):
    return hashlib.sha256(open(path, 'rb').read()).hexdigest()


