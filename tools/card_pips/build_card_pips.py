def write_sprites():
    changed = []
    for n in SPRITES:
        arr = render(n)
        path = os.path.join(IMG_DIR, n + '.png')
        if os.path.exists(path):
            old = np.array(Image.open(path).convert('RGBA'))
            if old.shape == arr.shape and (old == arr).all():
                continue
        Image.fromarray(arr, 'RGBA').save(path, optimize=True)
        changed.append(n)
    return changed


def write_gdt():
    text = open(GDT, 'rb').read().decode('ascii')
    add = [n for n in SPRITES if not gdt_has(text, n)]
    if not add:
        return []
    end = text.rstrip().rfind('}')
    text = text[:end] + ''.join(gdt_block(n) for n in add) + text[end:]
    open(GDT, 'wb').write(text.encode('ascii'))
    return add


def write_zone():
    raw, nl = zone_text()
    block = zone_block(nl)
    if ZBEGIN in raw:
        s = raw.index(ZBEGIN)
        e = raw.index(ZEND, s) + len(ZEND)
        new = raw[:s] + block + raw[e:]
    else:
        i = raw.index(ZANCHOR)
        j = raw.index(nl, i) + len(nl)
        new = raw[:j] + block + nl + raw[j:]
    if new != raw:
        open(ZONE, 'wb').write(new.encode('utf-8'))
        return True
    return False


def load_manifest():
    if os.path.exists(MANIFEST):
        return json.load(open(MANIFEST, encoding='utf-8'))
    return {'cards': {}}


def save_manifest(m):
    os.makedirs(os.path.dirname(MANIFEST), exist_ok=True)
    json.dump(m, open(MANIFEST, 'w', encoding='utf-8'), indent=1, sort_keys=True)


def paint_cards():
    os.makedirs(PARK, exist_ok=True)
    man = load_manifest()
    done, skipped, refused = [], [], []
    for n in zoned_cards():
        path = os.path.join(IMG_DIR, n + '.png')
        if not os.path.exists(path):
            refused.append((n, 'missing PNG'))
            continue
        img = Image.open(path)
        mode = img.mode
        a = np.array(img.convert('RGBA'))
        if a.shape[:2] != (CARD_H, CARD_W):
            refused.append((n, 'size %dx%d' % (a.shape[1], a.shape[0])))
            continue
        if band_clean(a):
            skipped.append(n)
            continue
        try:
            out, dots = paint_out(a)
        except ValueError as e:
            refused.append((n, str(e)))
            continue
        park = os.path.join(PARK, n + '.png')
        if not os.path.exists(park):
            shutil.copy2(path, park)
        before = sha(path)
        Image.fromarray(out, 'RGBA').save(path, optimize=True)
        man['cards'][n] = {'original_sha256': man['cards'].get(n, {}).get('original_sha256', before),
                           'painted_sha256': sha(path), 'dots': dots, 'source_mode': mode}
        done.append((n, dots))
    save_manifest(man)
    return done, skipped, refused


def restore():
    man = load_manifest()
    back = 0
    for n in sorted(man.get('cards', {})):
        park = os.path.join(PARK, n + '.png')
        if os.path.exists(park):
            shutil.copy2(park, os.path.join(IMG_DIR, n + '.png'))
            back += 1
    print('restored %d original card(s) from %s' % (back, PARK))
    print('the sprites, GDT blocks and zone block are left in place; the live row then sits over the baked dots.')


