def gdt_block(name):
    return ('\t"%s" ( "image.gdf" )\n\t{\n'
            '\t\t"arabicUnsafe" "0"\n'
            '\t\t"baseImage" "source_data/tod_ui_images/_images/%s.png"\n'
            '\t\t"clampU" "1"\n\t\t"clampV" "1"\n'
            '\t\t"colorSRGB" "1"\n'
            '\t\t"compressionMethod" "compressed high color"\n'
            '\t\t"coreSemantic" "sRGB3chAlpha"\n'
            '\t\t"doNotResize" "0"\n\t\t"forceStreaming" "0"\n\t\t"fromAlpha" "0"\n'
            '\t\t"imageType" "Texture"\n\t\t"mipBase" "1/1"\n\t\t"mipMode" "Average"\n'
            '\t\t"noMipMaps" "1"\n\t\t"noPicMip" "1"\n\t\t"premulAlpha" "0"\n'
            '\t\t"semantic" "diffuseMap"\n\t\t"streamable" "1"\n'
            '\t\t"textureAtlasColumnCount" "1"\n\t\t"textureAtlasRowCount" "1"\n'
            '\t\t"type" "image"\n\t}\n') % (name, name)


def gdt_has(text, name):
    return re.search(r'^\t"%s" \( "image\.gdf" \)' % re.escape(name), text, re.M) is not None


def zone_block(nl):
    return nl.join([ZBEGIN] + ['image,' + n for n in SPRITES] + [ZEND])


def zone_text():
    raw = open(ZONE, 'rb').read().decode('utf-8')
    nl = '\r\n' if '\r\n' in raw else '\n'
    return raw, nl


