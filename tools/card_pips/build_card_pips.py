def plan(n, owned, gain):
    """Mirror of tod_upgrade.lua PipPlan: returns (centres_x, scale)."""
    n = max(1, min(10, n))
    if n <= 7:
        k, p = 1.0, float(PIP_PITCH)
    else:
        k = min(1.0, (PIP_USABLE_W - 3.0 * (n - 1)) / (2 * R_HALO * n))
        p = min(float(PIP_PITCH), (PIP_USABLE_W - 2 * R_HALO * k) / (n - 1))
    xs = [PIP_CX + (i - (n + 1) / 2.0) * p for i in range(1, n + 1)]
    return xs, k


def paste(canvas, sprite, cx, cy, k, alpha=1.0):
    s = Image.fromarray(sprite, 'RGBA')
    w = max(1, int(round(s.width * k)))
    if w != s.width:
        s = s.resize((w, w), Image.LANCZOS)
    if alpha < 1.0:
        arr = np.array(s)
        arr[..., 3] = (arr[..., 3] * alpha).astype(np.uint8)
        s = Image.fromarray(arr, 'RGBA')
    canvas.alpha_composite(s, (int(round(cx - w / 2.0)), int(round(cy - w / 2.0))))


def preview(out_dir):
    os.makedirs(out_dir, exist_ok=True)
    spr = {n: render(n) for n in SPRITES}
    gain_of = {1: 'i_tod_cardpip_gain_regular', 2: 'i_tod_cardpip_gain_super', 3: 'i_tod_cardpip_gain_ultimate'}
    glow_of = {1: 'i_tod_cardpip_glow_regular', 2: 'i_tod_cardpip_glow_super', 3: 'i_tod_cardpip_glow_ultimate'}
    scenes = [
        ('headshot_super_lv2of5', 'i_tod_card_headshot_super', 5, 2, 2, 2),
        ('headshot_regular_lv2of5', 'i_tod_card_headshot_regular', 5, 2, 1, 1),
        ('headshot_ultimate_lv0of5', 'i_tod_card_headshot_ultimate', 5, 0, 3, 3),
        ('damage_ultimate_lv4of10', 'i_tod_card_damage_ultimate', 10, 4, 3, 3),
        ('dmg_reduction_super_lv6of9', 'i_tod_card_dmg_reduction_super', 9, 6, 2, 2),
        ('mag_size_regular_lv2of3', 'i_tod_card_mag_size_regular', 3, 2, 1, 1),
        ('perkslots_super_lv1of5', 'i_tod_card_perkslots_super', 5, 1, 2, 2),
        ('tier_assault_2', 'i_tod_card_tier_assault_2', 3, 1, 1, 'tier'),
    ]
    sheet = []
    for tag, card, n, owned, gain, rar in scenes:
        base = Image.open(os.path.join(IMG_DIR, card + '.png')).convert('RGBA')
        for phase in ('low', 'high'):
            c = base.copy()
            xs, k = plan(n, owned, gain)
            for i, x in enumerate(xs, 1):
                if owned < i <= owned + gain:
                    g = glow_of[3 if rar == 'tier' else rar]
                    paste(c, spr[g], x, PIP_CY, k * (PULSE_HI[1] if phase == 'high' else PULSE_LO[1]), PULSE_HI[0] if phase == 'high' else PULSE_LO[0])
            for i, x in enumerate(xs, 1):
                if i <= owned:
                    name = 'i_tod_cardpip_owned'
                elif i <= owned + gain:
                    name = 'i_tod_cardpip_gain_tier' if rar == 'tier' else gain_of[rar]
                else:
                    name = 'i_tod_cardpip_empty'
                paste(c, spr[name], x, PIP_CY, k)
                if owned < i <= owned + gain and phase == 'high':
                    paste(c, spr['i_tod_cardpip_shine'], x, PIP_CY, k, PULSE_HI[2])
            # the card as drawn at 1080p (234 canvas units x 1.5 = 351 px wide)
            small = c.resize((351, 527), Image.LANCZOS)
            small.save(os.path.join(out_dir, '%s_%s_1080p.png' % (tag, phase)))
            zoom = c.crop((140, 940, 628, 1100)).resize((976, 320), Image.LANCZOS)
            zoom.save(os.path.join(out_dir, '%s_%s_zoom.png' % (tag, phase)))
            sheet.append(small)
    cols = 4
    rows = (len(sheet) + cols - 1) // cols
    W, H = 351, 527
    board = Image.new('RGBA', (cols * (W + 12) + 12, rows * (H + 12) + 12), (14, 16, 26, 255))
    for i, im in enumerate(sheet):
        board.alpha_composite(im, (12 + (i % cols) * (W + 12), 12 + (i // cols) * (H + 12)))
    board.save(os.path.join(out_dir, 'contact_sheet_1080p.png'))
    print('preview written to %s (%d scenes x low/high pulse)' % (out_dir, len(scenes)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--install', action='store_true')
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--restore', action='store_true')
    ap.add_argument('--preview', metavar='DIR')
    ap.add_argument('--dry-run', action='store_true', help='with --install: report the card pass, write nothing')
    args = ap.parse_args()
    if args.check:
        sys.exit(check())
    if args.restore:
        restore()
        return
    if args.install:
        if args.dry_run:
            for n in zoned_cards():
                a = np.array(Image.open(os.path.join(IMG_DIR, n + '.png')).convert('RGBA'))
                if band_clean(a):
                    print('  clean   %s' % n)
                    continue
                try:
                    _, dots = paint_out(a)
                    print('  paint   %s  (%d dots, panel %s)' % (n, dots, panel_colour(a)))
                except ValueError as e:
                    print('  REFUSE  %s  %s' % (n, e))
            rows, worst = validate(PARK)
            for n, e in rows:
                print('  fit     %s  %s' % (n, 'n/a' if e is None else '%.2f' % e))
            return
        rows, worst = validate(PARK)
        changed = write_sprites()
        added = write_gdt()
        zone = write_zone()
        done, skipped, refused = paint_cards()
        print('sprites written: %d (%s)' % (len(changed), ', '.join(changed) or 'all current'))
        print('GDT blocks added: %d   zone block %s' % (len(added), 'written' if zone else 'current'))
        print('cards painted: %d   already clean: %d   refused: %d' % (len(done), len(skipped), len(refused)))
        for n, why in refused:
            print('  REFUSED %s: %s' % (n, why))
        for n, e in rows:
            print('  fit %s: %s' % (n, 'n/a' if e is None else 'mean error %.2f' % e))
        print('originals parked in %s' % PARK)
        sys.exit(1 if refused else 0)
    if args.preview:
        preview(args.preview)
        return
    ap.print_help()


if __name__ == '__main__':
    main()
