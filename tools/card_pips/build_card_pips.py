def check():
    errs = []
    for n in SPRITES:
        path = os.path.join(IMG_DIR, n + '.png')
        if not os.path.exists(path):
            errs.append('missing sprite %s.png (run --install)' % n)
            continue
        have = np.array(Image.open(path).convert('RGBA'))
        want = render(n)
        if have.shape != want.shape or not (have == want).all():
            errs.append('sprite %s.png differs from the generator (run --install)' % n)
    gdt = open(GDT, 'rb').read().decode('ascii')
    for n in SPRITES:
        if not gdt_has(gdt, n):
            errs.append('no image.gdf block for %s in tod_ui_images.gdt' % n)
    raw, nl = zone_text()
    if zone_block(nl) not in raw:
        errs.append('the generated card_pips zone block is missing or edited by hand')
    cards = zoned_cards()
    dirty = []
    for n in cards:
        path = os.path.join(IMG_DIR, n + '.png')
        if not os.path.exists(path):
            continue        # lint_tod_assets owns missing images
        a = np.array(Image.open(path).convert('RGBA'))
        if a.shape[:2] != (CARD_H, CARD_W) or not band_clean(a):
            dirty.append(n)
    if dirty:
        errs.append('%d zoned card(s) still carry BAKED level dots under the live row (run --install): %s'
                    % (len(dirty), ', '.join(dirty[:12]) + (' ...' if len(dirty) > 12 else '')))
    errs += lua_lockstep_errors()
    rows, worst = validate(PARK)
    if worst > 2.0:
        errs.append('the sprites drifted from the baked dots: mean error %.2f > 2.0' % worst)
    if errs:
        print('card_pips --check FAILED:')
        for e in errs:
            print('  - ' + e)
        return 1
    fit = ', '.join('%s %.2f' % (n.replace('i_tod_cardpip_', ''), e) for n, e in rows if e is not None)
    print('card_pips --check OK: %d sprites, GDT + zone block, %d zoned cards with no baked dots, Lua lockstep; '
          'sprite vs baked dot mean error: %s' % (len(SPRITES), len(cards), fit or 'n/a (no originals parked)'))
    return 0


