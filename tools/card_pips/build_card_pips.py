# LOCKSTEP with the Lua
LUA_LOCKSTEP = {
    'PIP_CX': PIP_CX, 'PIP_CY': PIP_CY, 'PIP_PITCH': PIP_PITCH,
    'PIP_USABLE_W': PIP_USABLE_W, 'PIP_HALO_R': R_HALO,
    'PIP_SPRITE': SPRITE, 'PIP_GLOW': GLOW,
}


def lua_lockstep_errors():
    errs = []
    try:
        lua = open(LUA, encoding='utf-8').read()
    except OSError as e:
        return ['cannot read %s: %s' % (LUA, e)]
    for k, v in LUA_LOCKSTEP.items():
        m = re.search(r'\b%s\s*=\s*([0-9.]+)' % k, lua)
        if not m:
            errs.append('tod_upgrade.lua has no %s (LOCKSTEP with this tool: %s)' % (k, v))
        elif abs(float(m.group(1)) - float(v)) > 1e-6:
            errs.append('tod_upgrade.lua %s = %s, this tool says %s' % (k, m.group(1), v))
    for n in SPRITES:
        if ('"%s"' % n) not in lua:
            errs.append('tod_upgrade.lua never registers %s' % n)
    return errs


