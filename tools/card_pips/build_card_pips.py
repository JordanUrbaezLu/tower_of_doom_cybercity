def validate(originals_dir):
    """Composite each sprite over the panel and diff it against the baked dot of the
    ORIGINAL card (the parked copy once the dots are painted out)."""
    rows, worst = [], 0.0
    for name, card, cx in VALIDATE:
        path = os.path.join(originals_dir, card)
        if not os.path.exists(path):
            path = os.path.join(IMG_DIR, card)
        a = np.array(Image.open(path).convert('RGB')).astype(float)
        x0, y0 = int(cx - SPRITE / 2), int(PIP_CY - SPRITE / 2)
        baked = a[y0:y0 + SPRITE, x0:x0 + SPRITE]
        if float(np.abs(baked - baked[0, 0]).max()) < 1:
            rows.append((name, None))      # the dots are gone from this copy
            continue
        panel = tuple(int(v) for v in a[1000, 200])
        ours = body_layers(name, bg=panel).rgb
        err = float(np.abs(ours - baked).mean())
        worst = max(worst, err)
        rows.append((name, err))
    return rows, worst


