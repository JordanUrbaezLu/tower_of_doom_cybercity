# rendering
def _grid(n):
    g = (np.arange(n * SS) + 0.5) / SS
    return np.meshgrid(g, g)


def _disc(n, cx, cy, r):
    X, Y = _grid(n)
    return ((((X - cx) ** 2 + (Y - cy) ** 2) <= r * r).reshape(n, SS, n, SS)).mean(axis=(1, 3))


def _feather(n, cx, cy, r0, r1):
    X, Y = _grid(n)
    d = np.sqrt((X - cx) ** 2 + (Y - cy) ** 2)
    return np.clip((r1 - d) / (r1 - r0), 0, 1).reshape(n, SS, n, SS).mean(axis=(1, 3))


class Layers:
    """Straight-alpha 'over' compositing into a premultiplied buffer."""

    def __init__(self, n, bg=None):
        self.n = n
        self.rgb = np.zeros((n, n, 3))
        self.a = np.zeros((n, n))
        if bg is not None:
            self.rgb[:] = np.array(bg, float)
            self.a[:] = 1.0

    def over(self, col, cov, alpha=1.0):
        k = cov * alpha
        self.rgb = self.rgb * (1 - k[..., None]) + np.array(col, float)[None, None, :] * k[..., None]
        self.a = self.a * (1 - k) + k

    def rgba(self):
        out = np.zeros((self.n, self.n, 4))
        safe = np.where(self.a > 1e-6, self.a, 1)
        out[..., :3] = self.rgb / safe[..., None]
        out[..., 3] = self.a * 255.0
        return np.clip(np.round(out), 0, 255).astype(np.uint8)


def body_layers(kind, bg=None):
    n, c = SPRITE, SPRITE / 2.0
    L = Layers(n, bg)
    if kind == 'i_tod_cardpip_empty':
        L.over(OUTLINE, _disc(n, c, c, R_OUT))
        L.over(EMPTY_IN, _disc(n, c, c, R_CORE))
        return L
    core, hl, halo = BODIES[kind]
    if halo:
        L.over(halo, _disc(n, c, c, R_HALO))
    L.over(OUTLINE, _disc(n, c, c, R_OUT))
    L.over(core, _disc(n, c, c, R_CORE))
    L.over(hl, _feather(n, c + HL_OFF, c + HL_OFF, HL_R0, HL_R1))
    return L


def render_glow(col):
    # a soft light: full under the dot (hidden by it), then a falloff that is gone by
    # r ~34 card px. The Lua breathes its alpha and size.
    n, c = GLOW, GLOW / 2.0
    X, Y = _grid(n)
    d = np.sqrt((X - c) ** 2 + (Y - c) ** 2)
    a = np.where(d <= 16.0, 1.0, np.exp(-((d - 16.0) / 8.5) ** 2))
    a = a.reshape(n, SS, n, SS).mean(axis=(1, 3))
    out = np.zeros((n, n, 4), np.uint8)
    out[..., 0], out[..., 1], out[..., 2] = col
    out[..., 3] = np.clip(np.round(a * 230), 0, 255).astype(np.uint8)
    return out


def render_shine():
    # white over the core only, brightest at the centre: the dot itself lights up
    n, c = SPRITE, SPRITE / 2.0
    X, Y = _grid(n)
    d = np.sqrt((X - c) ** 2 + (Y - c) ** 2)
    edge = np.clip((R_CORE - d) / 1.0, 0, 1)
    a = edge * (1.0 - 0.35 * np.clip(d / R_CORE, 0, 1) ** 2)
    a = a.reshape(n, SS, n, SS).mean(axis=(1, 3))
    out = np.zeros((n, n, 4), np.uint8)
    out[..., :3] = 255
    out[..., 3] = np.clip(np.round(a * 255), 0, 255).astype(np.uint8)
    return out


def render(name):
    if name in GLOWS:
        return render_glow(GLOWS[name])
    if name == 'i_tod_cardpip_shine':
        return render_shine()
    return body_layers(name).rgba()


